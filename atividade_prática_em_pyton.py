import matplotlib.pyplot as plt

class Livro:
    def __init__(self, titulo, autor, genero, quantidade):
        self.titulo = titulo
        self.autor = autor
        self.genero = genero
        self.quantidade = quantidade

    def __str__(self):
        return (f"Título: {self.titulo}, Autor: {self.autor}, "f"Gênero: {self.genero}, Quantidade: {self.quantidade}")

biblioteca = []

def cadastrar_livro(titulo, autor, genero, quantidade):

    novo_livro = Livro(titulo, autor, genero, quantidade)
    biblioteca.append(novo_livro)
    print(f"Livro '{titulo}' cadastrado com sucesso!")

def listar_livros():

    if not biblioteca:
        print("Nenhum livro cadastrado.")
        return
        print("\n--- Livros disponíveis ---")
    for livro in biblioteca:
        print(livro)

def buscar_livro(titulo):

    for livro in biblioteca:
        if livro.titulo.lower() == titulo.lower():
            print(f"\nLivro encontrado: {livro}")
            return livro

def grafico_por_genero():
    if not biblioteca:
        print("Nenhum livro cadastrado para gerar o gráfico.")
        return
    generos = [livro.genero for livro in biblioteca]
    generos_unicos = list(set(generos))
    generos_unicos.sort()

    contagem = [generos.count(gen) for gen in generos_unicos]

    plt.bar(generos_unicos, contagem, color='royalblue')
    plt.xlabel("Gênero")
    plt.ylabel("Número de Livros")
    plt.title("Biblioteca - Livros por Gênero")
    plt.show()

cadastrar_livro("Drácula", "Bram Stoker", "Terror", 10)
